package rules

import (
	"fmt"
	"strings"
)

var domainTitle = map[string]string{
	"compose":    "Docker Compose",
	"kubernetes": "Kubernetes",
	"terraform":  "Terraform (AWS)",
}

// Markdown renders the rule catalogue; docs/RULES.md is generated from it.
func Markdown() string {
	var sb strings.Builder
	sb.WriteString("# CloudGraph rules\n\n")
	sb.WriteString("<!-- Generated by `cloudgraph rules --format markdown`. Do not edit by hand. -->\n\n")
	fmt.Fprintf(&sb, "%d rules. Findings feed the attack path engine; most of them come with a virtual fix for the what-if simulator.\n", len(All()))
	for _, d := range []string{"compose", "kubernetes", "terraform"} {
		fmt.Fprintf(&sb, "\n## %s\n\n| ID | Severity | Rule | Remediation |\n| --- | --- | --- | --- |\n", domainTitle[d])
		for _, r := range All() {
			if r.Domain != d {
				continue
			}
			fmt.Fprintf(&sb, "| `%s` | %s | %s | %s |\n", r.ID, r.Severity, r.Title, strings.ReplaceAll(r.Remediation, "|", `\|`))
		}
	}
	return sb.String()
}
