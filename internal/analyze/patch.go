package analyze

import (
	"fmt"
	"sort"
	"strings"

	"github.com/TroubieD3v/cloudgraph/internal/model"
)

// Patch renders the selected fixes as a zero-context unified diff that can be
// applied with `git apply --unidiff-zero`. Fixes without a mechanical edit
// (Terraform plans, multi-line YAML structures) are listed as manual steps.
// When files is non-nil, original lines are read from it; otherwise the
// recorded (secret-masked) lines are used.
func Patch(a *model.Analysis, fixIDs []string, files map[string][]string) (string, []string) {
	byID := map[string]*model.Fix{}
	for _, f := range a.Fixes {
		byID[f.ID] = f
	}
	perFile := map[string][]model.Edit{}
	manual := []string{}
	for _, id := range fixIDs {
		f := byID[id]
		if f == nil {
			continue
		}
		if len(f.Edits) == 0 {
			manual = append(manual, fmt.Sprintf("%s — %s (%s)", f.ID, f.Description, f.Target))
			continue
		}
		for _, e := range f.Edits {
			perFile[e.File] = append(perFile[e.File], e)
		}
	}

	var names []string
	for n := range perFile {
		names = append(names, n)
	}
	sort.Strings(names)

	var sb strings.Builder
	sb.WriteString("# Generated by CloudGraph what-if remediation. Review before applying.\n")
	sb.WriteString("# Apply with: git apply --unidiff-zero <this file>\n")
	for _, m := range manual {
		sb.WriteString("# MANUAL: " + m + "\n")
	}
	for _, name := range names {
		es := perFile[name]
		es = coalesceInserts(es)
		sort.SliceStable(es, func(i, j int) bool {
			if es[i].StartLine != es[j].StartLine {
				return es[i].StartLine < es[j].StartLine
			}
			return isInsert(es[i]) && !isInsert(es[j]) // inserts go before the line they precede
		})
		if len(es) > 0 && es[0].New {
			lines := strings.Split(es[0].Replace, "\n")
			fmt.Fprintf(&sb, "--- /dev/null\n+++ b/%s\n@@ -0,0 +1,%d @@\n", name, len(lines))
			for _, l := range lines {
				sb.WriteString("+" + l + "\n")
			}
			continue
		}
		fmt.Fprintf(&sb, "--- a/%s\n+++ b/%s\n", name, name)
		delta := 0
		lastEnd := 0
		for _, e := range es {
			if e.StartLine <= lastEnd {
				fmt.Fprintf(&sb, "# SKIPPED overlapping edit at line %d\n", e.StartLine)
				continue
			}
			if isInsert(e) {
				lastEnd = max(lastEnd, e.StartLine-1)
			} else {
				lastEnd = e.EndLine
			}
			var oldLines []string
			if e.EndLine >= e.StartLine {
				for l := e.StartLine; l <= e.EndLine; l++ {
					if src, ok := files[name]; ok && l-1 < len(src) {
						oldLines = append(oldLines, src[l-1])
					} else if i := l - e.StartLine; i < len(e.Old) {
						oldLines = append(oldLines, e.Old[i])
					}
				}
			}
			var newLines []string
			if e.Replace != "" {
				newLines = strings.Split(e.Replace, "\n")
			}
			oldCount := 0
			if e.EndLine >= e.StartLine {
				oldCount = e.EndLine - e.StartLine + 1
			}
			oldStart, newStart := e.StartLine, e.StartLine+delta
			if oldCount == 0 {
				oldStart = e.StartLine - 1
			}
			if len(newLines) == 0 {
				newStart = e.StartLine - 1 + delta
			}
			fmt.Fprintf(&sb, "@@ -%d,%d +%d,%d @@\n", oldStart, oldCount, newStart, len(newLines))
			for _, l := range oldLines {
				sb.WriteString("-" + l + "\n")
			}
			for _, l := range newLines {
				sb.WriteString("+" + l + "\n")
			}
			delta += len(newLines) - oldCount
		}
	}
	return sb.String(), manual
}

func isInsert(e model.Edit) bool { return e.EndLine < e.StartLine }

// coalesceInserts merges several insertions before the same line into one.
func coalesceInserts(es []model.Edit) []model.Edit {
	var out []model.Edit
	at := map[int]int{}
	for _, e := range es {
		if !isInsert(e) {
			out = append(out, e)
			continue
		}
		if i, ok := at[e.StartLine]; ok {
			out[i].Replace += "\n" + e.Replace
			continue
		}
		at[e.StartLine] = len(out)
		out = append(out, e)
	}
	return out
}
